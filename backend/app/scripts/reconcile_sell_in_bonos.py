"""Full reconcile of every brand bonus (sell-in-sell-out T3c-3).

The queue's consumer (the `sell_in.bono` worker) reconciles what the triggers
queue. This script, usable on its own, reconciles EVERY bonus (any state: a voided one voids what it generated) and
voids generated purchases whose operation was deleted, so the generated sell
ins match the bonuses and the invoiced units as they are now: the initial
backfill after deploy, or a repair. Same code the worker runs
(`app.services.sell_in.bonos.reconciliar`).

Idempotent: a re-run writes nothing. One short session and one commit per
bonus; `--dry-run` runs them all in one transaction rolled back at the end and
reports what the real run would change.
Pairs that cannot be reconciled (a USD bonus on an operation with no rate and
no BNA rate for its invoice date) are left as they were and listed in the
summary's `fallidas`; the exit code is then 1, else 0. Any other error stops a
real run partway: the bonuses reconciled before it stay committed, the failing
one is rolled back and the rest are not touched. Re-running is safe, since the
reconcile is idempotent: it finishes what is missing and rewrites nothing else.

Run from `backend/` with `-m` (the settings read `backend/.env` from there):
    cd /var/www/html/pricing-app/backend && ./venv/bin/python -m app.scripts.reconcile_sell_in_bonos --dry-run
    cd /var/www/html/pricing-app/backend && ./venv/bin/python -m app.scripts.reconcile_sell_in_bonos
"""

from __future__ import annotations

import argparse
import json
import sys
from typing import Callable, Optional

from sqlalchemy.orm import Session

from app.models.sell_in import SellInBonoMarca
from app.services.sell_in import bonos


def run_reconcile(*, session_factory: Callable[[], Session], dry_run: bool = False) -> dict:
    """Reconciles every bonus, one transaction each; returns the summary. Under `dry_run` every bonus runs
    in ONE transaction rolled back at the end, so each call sees what the previous ones would have written
    (the orphans are swept once, as in a real run) and the summary predicts the real run."""
    with session_factory() as db:
        ids = [bid for (bid,) in db.query(SellInBonoMarca.id).order_by(SellInBonoMarca.id)]
    summary = {"bonos": len(ids), "creadas": 0, "actualizadas": 0, "anuladas": 0, "fallidas": [], "dry_run": dry_run}
    # Every call also voids orphans whose operation was deleted; with no bonus one call still does.
    keys = [[bono_id] for bono_id in ids] or [[]]
    if dry_run:
        with session_factory() as db:
            try:
                for bono_ids in keys:
                    _sumar(summary, bonos.reconciliar(db, bono_ids=bono_ids))
            finally:
                db.rollback()
        return summary
    for bono_ids in keys:
        with session_factory() as db:
            result = bonos.reconciliar(db, bono_ids=bono_ids)
            db.commit()
        _sumar(summary, result)
    return summary


def _sumar(summary: dict, result: bonos.ReconcileResult) -> None:
    summary["creadas"] += result.creadas
    summary["actualizadas"] += result.actualizadas
    summary["anuladas"] += result.anuladas
    summary["fallidas"] += [[b, p, error] for (b, p), error in sorted(result.fallidas.items())]


def _build_parser() -> argparse.ArgumentParser:
    parser = argparse.ArgumentParser(description="Reconcile the sell ins generated by every brand bonus.")
    parser.add_argument("--dry-run", action="store_true", help="report what would change and roll back")
    return parser


def main(argv: Optional[list[str]] = None) -> int:
    args = _build_parser().parse_args(argv)
    from app.core import database  # resolved at call time, so tests can point it elsewhere

    summary = run_reconcile(session_factory=database.SessionLocal, dry_run=args.dry_run)
    print(json.dumps(summary, ensure_ascii=False, default=str))
    return 1 if summary["fallidas"] else 0


if __name__ == "__main__":  # pragma: no cover
    sys.exit(main())
