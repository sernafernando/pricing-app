const DAYS = 90;

// Deterministic "market" series: a base level, a slope and a wobble.
function series(base, slope, wobble, { gapsEvery = 0 } = {}) {
  return Array.from({ length: DAYS }, (_, i) => {
    if (gapsEvery && i % gapsEvery === 0) return null;
    const value = base + slope * (i / DAYS) + wobble * Math.sin(i / 9);
    return Math.round(value * 10) / 10;
  });
}

function unitSeries(perDay, slope = 0) {
  return Array.from({ length: DAYS }, (_, i) => Math.max(0, Math.round(perDay + slope * (i / DAYS) + Math.sin(i * 1.7))));
}

